"""Convert the generated appendix markdown into LaTeX.

The input is machine-generated by appendices.py and uses only headings, paragraphs and pipe tables,
so a narrow converter is safer and more predictable than a general-purpose one.

    python appendices.py appendices.md
    python md2tex.py appendices.md appendices_tex.tex

Two things the converter has to get right, both learned from breaking them:

* Cells are split on *unescaped* pipes only. An invariant name such as ``\\|E_f\\| = 3`` carries
  escaped pipes, and splitting on those silently produced a six-column row in a four-column table,
  which LaTeX then set 486 pt too wide.
* Tables are sized to the page. A first column holding prose gets a fixed-width ``p`` column so it
  wraps, and a table with many columns is shrunk with ``\\resizebox`` rather than left to overflow.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

SPECIAL = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#", "$": r"\$"}
UNICODE = {"—": "---", "–": "--", "×": r"$\times$", "≈": r"$\approx$", "≪": r"$\ll$",
           "≤": r"$\leq$", "≥": r"$\geq$", "−": "$-$", "’": "'", "“": "``", "”": "''",
           "|": r"\textbar{}"}
SPLIT = re.compile(r"(?<!\\)\|")        # a pipe that is not escaped
WIDE_COLS = 8                            # beyond this, shrink the table to the text width
PROSE_CHARS = 28                         # a first column longer than this wraps instead of running on


def esc(s: str) -> str:
    s = s.replace(r"\|", "|")           # drop the markdown pipe guard now that splitting is done
    for a, b in SPECIAL.items():
        s = s.replace(a, b)
    for a, b in UNICODE.items():
        s = s.replace(a, b)
    return s


def inline(s: str) -> str:
    """Escape, then re-apply bold, italic and code spans as LaTeX."""
    s = esc(s)
    s = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", s)
    s = re.sub(r"(?<!\*)\*(?!\*)(.+?)(?<!\*)\*(?!\*)", r"\\emph{\1}", s)
    s = re.sub(r"`(.+?)`", r"\\texttt{\1}", s)
    return s


def is_rule(cells: list[str]) -> bool:
    return bool(cells) and all(set(c.strip()) <= set("-: ") for c in cells)


def table(rows: list[list[str]]) -> list[str]:
    n = max(len(r) for r in rows)
    rows = [r + [""] * (n - len(r)) for r in rows]
    # drop columns that are empty in every row -- a ragged source row would otherwise widen the table
    keep = [j for j in range(n) if any(r[j].strip() for r in rows)]
    rows = [[r[j] for j in keep] for r in rows]
    n = len(keep)
    # Any column holding prose gets a fixed-width p column so it wraps. The long column is not
    # always the first -- the invariants table carries its prose in column three -- so decide per
    # column and share the available width between however many qualify.
    widths = [max(len(r[j]) for r in rows) for j in range(n)]
    prose = [j for j in range(n) if widths[j] > PROSE_CHARS]
    share = 0.62 / len(prose) if prose else 0.0
    spec = "".join((r"p{%.2f\textwidth}" % share) if j in prose else ("l" if j == 0 else "c")
                   for j in range(n))
    body = [r"\toprule"]
    for k, r in enumerate(rows):
        body.append(" & ".join(inline(c) for c in r) + r" \\")
        if k == 0:
            body.append(r"\midrule")
    body.append(r"\bottomrule")
    inner = [r"\begin{tabular}{" + spec + "}"] + body + [r"\end{tabular}"]
    if n > WIDE_COLS:
        inner = [r"\resizebox{\textwidth}{!}{%"] + inner + ["}"]
    return [r"\begin{center}\footnotesize"] + inner + [r"\end{center}", ""]


def convert(lines: list[str]) -> list[str]:
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        if line.startswith("### "):
            out.append(r"\subsection{" + inline(line[4:]) + "}")
        elif line.startswith("## "):
            out.append(r"\section{" + inline(line[3:]) + "}")
        elif line.lstrip().startswith("|"):
            block = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                block.append(lines[i].strip())
                i += 1
            rows = [[c.strip() for c in SPLIT.split(r.strip("|"))] for r in block]
            rows = [r for r in rows if not is_rule(r)]
            if rows:
                out += table(rows)
            continue
        elif line.strip():
            out.append(inline(line))
        else:
            out.append("")
        i += 1
    return out


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    tex = convert(src.read_text(encoding="utf-8").splitlines())
    dst.write_text("\n".join(tex).rstrip() + "\n", encoding="utf-8")
    bs = chr(92)
    print(f"wrote {dst}: {len(tex)} lines, "
          f"{sum(1 for l in tex if l.startswith(bs + 'section'))} sections, "
          f"{sum(1 for l in tex if l.startswith(bs + 'begin{tabular}'))} tables, "
          f"{sum(1 for l in tex if l.startswith(bs + 'resizebox'))} shrunk to fit")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
